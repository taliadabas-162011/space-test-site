import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const source = await readFile(process.argv[2] || new URL('../design/crew-insights.js', import.meta.url), 'utf8');
const { compareHistory } = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
const now = Date.parse('2026-11-09T18:00:00Z');
const entry = (day, value, context = 'rest', hour = 12) => ({ time: new Date(now - day * 86400000 - (18-hour)*3600000).toISOString(), value, context });
const readings = [entry(4, 60), entry(3, 62), entry(2, 80, 'after-activity'), entry(2, 64), entry(1, 66), entry(1, 68, 'rest', 15), entry(0, 76)];
const result = compareHistory('pulse', readings, now);
assert.equal(result.days, 4);
assert.deepEqual(result.baseline, [63]);
assert.deepEqual(result.delta, [13]);
assert.equal(compareHistory('pulse', [entry(3, 60), entry(2, 61), entry(1, 62), entry(0, 70, '')], now), null);
assert.equal(compareHistory('pulse', [entry(2, 60), entry(1, 62), entry(0, 70)], now), null);
const pressure = [entry(3, { systolic: 120, diastolic: 70 }), entry(2, { systolic: 118, diastolic: 72 }), entry(1, { systolic: 122, diastolic: 74 }), entry(0, { systolic: 125, diastolic: 76 })];
assert.deepEqual(compareHistory('pressure', pressure, now).baseline, [120, 72]);
assert.deepEqual(compareHistory('pressure', pressure, now).delta, [5, 4]);
assert.equal(compareHistory('water', [entry(3, 1), entry(2, 2), entry(1, 2), entry(0, 0)], now).delta[0], -2);
assert.equal(compareHistory('pulse', [entry(40, 60), entry(39, 61), entry(38, 62), entry(0, 75)], now), null);
console.log('Comparisons use prior days, matching context, valid values, and a descriptive median.');
const temperatures=[3,2,1].map(day=>({...entry(day,36.5),site:'ear'}));temperatures.push({...entry(0,37),site:'oral'});
assert.equal(compareHistory('temperature',temperatures,now),null,'different temperature sites cannot establish a personal baseline');
