import assert from 'node:assert/strict';
import { createSceneOrbit, sceneFitDistance } from '../design/crew-scene-orbit.js';
const orbit = createSceneOrbit();
const settle = () => orbit.update(1, true);
orbit.begin(0); orbit.move(.2, .1, 20);
assert.equal(settle().yaw, -.76);
assert.equal(settle().pitch, .065);
orbit.end(25);
assert.ok(settle().yaw < -.76, 'a recent release carries a small bounded continuation');
orbit.begin(30); orbit.move(500, -500, 50); orbit.end(55);
assert.equal(settle().yaw, -1.15); assert.equal(settle().pitch, -.22);
orbit.zoom(-500); assert.equal(settle().zoom, -1.3);
orbit.zoom(500); assert.equal(settle().zoom, 1.2);
orbit.reset(); assert.deepEqual({...settle()}, {yaw:0,pitch:0,zoom:0});
orbit.begin(100); orbit.move(.1, 0, 110); orbit.end(300);
assert.equal(settle().yaw, -.38, 'holding before release does not fling');
orbit.reset(); orbit.begin(400); orbit.move(.1, 0, 410); orbit.end(420, false, true);
assert.equal(settle().yaw, -.38, 'reduced motion has no release continuation');
orbit.reset(); orbit.begin(500); orbit.move(.1, 0, 510); orbit.end(520, true);
assert.equal(settle().yaw, -.38, 'pointer cancellation does not fling');
orbit.reset(); settle(); orbit.rotate(.5,.1);
const halfway={...orbit.update(.016)};assert.ok(halfway.yaw>0&&halfway.yaw<.5);
assert.equal(settle().yaw,.5,'reduced motion goes directly to the requested position');
console.log('Scene orbit keeps drag, zoom and release bounded, resets and honors reduced motion.');

const wide=sceneFitDistance({width:.3,height:.6},1.7);
const narrow=sceneFitDistance({width:.15,height:.6},1);
assert.ok(narrow>wide,'a narrow scene slot increases distance to keep the suit clear of readings');
assert.ok(sceneFitDistance({width:.3,height:.3},1.7)>wide,'a short scene slot also increases distance');
assert.equal(sceneFitDistance(null,1),6.1);
assert.equal(sceneFitDistance({width:NaN,height:.5},1),6.1);
assert.equal(sceneFitDistance({width:.3,height:.5},0),6.1);
